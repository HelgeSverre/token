pub(crate) fn placement(setting: Setting) -> Option<(CategoryId, &'static Group)> {
    categories().iter().find_map(|&category| {
        category
            .page()
            .groups
            .iter()
            .find(|group| group.settings.contains(&setting))
            .map(|group| (category, group))
    })
}

/// Ordinary rows used both by the preferences list and by specialized pages.
pub(crate) fn preference_rows(category: CategoryId) -> impl Iterator<Item = super::SettingRow> {
    category.page().groups.iter().flat_map(|group| {
        group.settings.iter().map(|&setting| super::SettingRow {
            kind: super::RowKind::Preset(setting),
            section: group.title,
            name: setting.descriptor().name.into(),
            description: setting.descriptor().description.into(),
        })
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn settings_catalog_has_unique_keys_and_exactly_one_primary_placement() {
        let mut keys = HashSet::new();
        let mut groups = HashSet::new();
        let mut settings = HashSet::new();
        let mut categories_seen = HashSet::new();
        for &category in categories() {
            assert!(categories_seen.insert(category.page().key));
            assert_eq!(CategoryId::from_name(category.label()), Some(category));
            assert_eq!(categories()[category.index()], category);
            for group in category.page().groups {
                assert!(groups.insert(group.id), "duplicate group {:?}", group.id);
                assert!(!group.settings.is_empty());
                for &setting in group.settings {
                    assert!(settings.insert(setting), "duplicate placement: {setting:?}");
                    assert!(
                        keys.insert(setting.descriptor().key),
                        "duplicate key: {setting:?}"
                    );
                }
            }
        }
        assert_eq!(settings, Setting::ALL.iter().copied().collect());
    }
}
