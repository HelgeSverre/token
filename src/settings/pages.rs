//! Preferences navigation and placement. Labels never select application behavior.
use super::catalog::Setting;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(crate) struct GroupId(pub &'static str);

#[derive(Debug)]
pub(crate) struct Group {
    pub id: GroupId,
    pub title: &'static str,
    pub settings: &'static [Setting],
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum PageKind {
    Preferences,
    Formatters,
    LanguageServers,
    AiProviders,
    Keymap,
}

#[derive(Debug)]
pub(crate) struct Page {
    key: &'static str,
    label: &'static str,
    pub kind: PageKind,
    pub groups: &'static [Group],
}

macro_rules! pages {
    ($($id:ident => $page:expr),+ $(,)?) => {
        /// Stable navigation identity, independent of labels and display order.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        pub enum CategoryId { $($id),+ }

        pub fn categories() -> &'static [CategoryId] {
            &[$(CategoryId::$id),+]
        }

        impl CategoryId {
            pub(crate) fn page(self) -> &'static Page {
                match self { $(Self::$id => &$page),+ }
            }
        }
    };
}

impl CategoryId {
    pub fn label(self) -> &'static str {
        self.page().label
    }

    pub fn index(self) -> usize {
        // Both the enum and the navigation list are generated by pages!.
        categories()
            .iter()
            .position(|id| *id == self)
            .expect("every category is declared in pages!")
    }

    /// Accept stable keys as well as display names for screenshot scenarios.
    pub fn from_name(name: &str) -> Option<Self> {
        categories().iter().copied().find(|id| {
            id.page().key.eq_ignore_ascii_case(name) || id.label().eq_ignore_ascii_case(name)
        })
    }
}

